"""Build the LOCAL, gitignored fixtures for the dev-only viewer demo harness.

The demo harness (frontend route /dev/viewer-demo, DEV builds only) renders the
real ViewerApp without a backend or a login. It needs the responses the backend
would send for ONE public case. To keep those responses faithful they are
produced by the backend's own code on the public volume:

  * imaging metadata      -> ImagingService.load_nifti        (/imaging/metadata)
  * server PNG slices     -> ImagingService.process_image     (/imaging/process,
                             the legacy 2D path, kept as fallback)
  * lesion statistics     -> lesion_analysis_service.analyze_lesions
  * DIS assessment        -> lesion_analysis_service.compute_dis_criteria
  * binary mask           -> RC-031 internal (k, a0, a1) layout = transpose(2, 0, 1)

Data source (read-only, public, CC-BY): open_ms_data cross_sectional/MNI
patient01 (Lesjak et al., Neuroinformatics 2017). Nothing is uploaded anywhere.

Usage (repo root):
    backend/venv/Scripts/python.exe scripts/viewer/build_demo_fixtures.py [path/to/data/external]

Output: frontend/.dev-data/viewer-demo/   (gitignored, ~60 MB, never committed,
served only by the Vite dev server — see frontend/vite.config.ts).
"""
from __future__ import annotations

import asyncio
import json
import os
import shutil
import struct
import sys
from pathlib import Path

import numpy as np
import nibabel as nib

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "backend"))
os.environ.setdefault("GOOGLE_APPLICATION_CREDENTIALS", "nonexistent")

from app.services.imaging_service import ImagingService  # noqa: E402
from app.services.lesion_analysis_service import analyze_lesions, compute_dis_criteria  # noqa: E402

# Windows-only harness shim (see build_parity_fixture.py): no value changes.
_orig_load = nib.load
nib.load = lambda path, **kw: _orig_load(path, mmap=False, **kw)  # type: ignore[assignment]

OUT = REPO / "frontend" / ".dev-data" / "viewer-demo"
CASE = "open_ms_data/cross_sectional/MNI/patient01"
FILES = {
    "flair": "FLAIR_N4_noneck_reduced_winsor_regtoFLAIR_brain_N4_regtoMNI.nii.gz",
    "t1": "T1_N4_noneck_reduced_winsor_regtoFLAIR_brain_N4_regtoMNI.nii.gz",
    "gold": "GOLD_STANDARD_N4_noneck_reduced_winsor_regtoFLAIR_regtoMNI.nii.gz",
}
LABELS = [
    {"id": 0, "name": "Background", "color": "#000000", "opacity": 0.0, "visible": False},
    {"id": 1, "name": "Lesion", "color": "#FF4D4D", "opacity": 0.6, "visible": True},
]


def main(external: Path):
    src = external / CASE
    OUT.mkdir(parents=True, exist_ok=True)
    svc = ImagingService()

    for key in ("flair", "t1", "gold"):
        shutil.copyfile(src / FILES[key], OUT / f"{key}.nii.gz")

    for key in ("flair", "t1"):
        raw = (OUT / f"{key}.nii.gz").read_bytes()
        _, meta = svc.load_nifti(raw)
        (OUT / f"metadata-{key}.json").write_text(json.dumps({
            "format": "nifti",
            "metadata": json.loads(meta.model_dump_json()),
            "file_info": {"name": f"{key}.nii.gz", "path": key, "size": len(raw),
                          "content_type": "application/gzip"},
        }))
        series = asyncio.run(svc.process_image(raw, f"{key}.nii.gz", (0, 500)))
        (OUT / f"process-{key}.json").write_text(series.model_dump_json())
        print(f"{key}: {meta.rows}x{meta.columns}x{meta.slices} orient={meta.anatomical_orientation}")

    gold = nib.load(str(OUT / "gold.nii.gz"))
    native = np.asarray(gold.get_fdata()).round().astype(np.uint8)
    internal = np.ascontiguousarray(np.transpose(native, (2, 0, 1)))  # (k, a0, a1)
    d, h, w = internal.shape
    with open(OUT / "mask-gold.bin", "wb") as fh:
        fh.write(struct.pack("<III", d, h, w))
        fh.write(internal.tobytes())
    zi, zj, zk = (float(z) for z in gold.header.get_zooms()[:3])
    spacing = (zk, zi, zj)  # (dz, dy, dx) for the internal (k, a0, a1) array
    label_map = {1: "Lesion"}
    lesions = analyze_lesions(internal, spacing, label_map)
    lesions["segmentation_id"] = "demo-seg-gold"
    (OUT / "lesions-gold.json").write_text(json.dumps(lesions, default=float))
    dis = compute_dis_criteria(internal, label_map, spacing)
    dis["segmentation_id"] = "demo-seg-gold"
    (OUT / "dis-gold.json").write_text(json.dumps(dis, default=float))
    print(f"mask {internal.shape} lesions={lesions.get('total_count')} burden={lesions.get('total_burden_ml')} ml")

    (OUT / "labels.json").write_text(json.dumps(LABELS))
    (OUT / "SOURCE.txt").write_text(
        "Public data: open_ms_data (CC-BY), cross_sectional/MNI/patient01.\n"
        "Lesjak Z. et al., Neuroinformatics 2017, doi:10.1007/s12021-017-9348-7.\n"
        "Generated by scripts/viewer/build_demo_fixtures.py with the backend's own code.\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    ext = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "data" / "external"
    if not (ext / CASE).exists():
        sys.exit(f"public case not found under {ext} — pass the data/external path")
    main(ext)
