"""M1 (thirteenth review of PR #81): the SERVER's own decisions for the single-study inputs the model-based test of the
browser card plays — so the fake server in BrowserFlamesCard.model.test.tsx answers with the real rule, never a copy of
it. Keys: sequence | attested | skull [| run confirmed by a valid run token] [| nover: the file's version could not be
established]. Fourteenth review (K2): ``run_token`` says how the REAL server answers a final consultation presented again
with the same token and the identical request (a lost answer): replayed, or refused. Recomputed and compared by
backend/tests/unit/test_rc122_review13.py (a drift fails CI).
Output: frontend/src/config/qualityGate.card_model.v1.json. Run from the repository root with the backend venv Python.
DRAFT, PENDING owner approval."""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "frontend/src/config/qualityGate.card_model.v1.json")
KEEP = ("gate_version", "policy_version", "mode", "decision", "ai_may_run", "ai_output_allowed", "codes", "checks",
        "attestable_visits", "actions")


def decisions():
    sys.path.insert(0, os.path.join(ROOT, "backend"))
    from app.services import quality_gate as qg
    out = {}
    for sequence in ("missing", "FLAIR"):
        for attested in (False, True):
            for skull in ("pending", "stripped"):
                for confirmed in ((None,) if skull == "pending" else (True, False)):
                    for known in (True, False):
                        visit = {"sequence": sequence, "physician_confirmed_flair": attested, "skull": skull,
                                 "scanner": None, "thickness": {"state": "native", "effective_mm": 1.0}}
                        inputs = {"mode": "single", "platform": {"allowed": True, "code": None}, "visits": [visit],
                                  "version_established": known}
                        if confirmed is not None:
                            inputs["run_confirmed"] = confirmed
                        result = qg.evaluate(inputs)
                        key = (f"{sequence}|{str(attested).lower()}|{skull}"
                               + ("" if confirmed is None else f"|{str(confirmed).lower()}") + ("" if known else "|nover"))
                        out[key] = {k: result[k] for k in KEEP}
    return out


def run_token_semantics():
    """K2: does the real server REPLAY a final consultation presented again with the same token and the identical
    request (its first answer was lost), or refuse it? Exercised on the server's own single-use store (memory)."""
    os.environ.setdefault("QUALITY_GATE_TOKEN_SECRET", "card-model-fixture")
    os.environ["QUALITY_GATE_RUN_TOKEN_STORE"] = "memory"
    sys.path.insert(0, os.path.join(ROOT, "backend"))
    from app.services import quality_gate as qg
    qg._RUN_TOKEN_MEMORY = None
    f, v, u = "patients/p/studies/s/series/x/f.nii.gz", "10:v1:2026-11-13", "id-card-model"
    token = qg.run_token(f, v, u, False)
    args = {"file_id": f, "version": v, "user_id": u, "attested": False, "skull": "stripped"}
    if not hasattr(qg, "claim_final"):
        first = qg.spend_run_token(token, **{k: a for k, a in args.items() if k != "skull"})  # the server before K2
        again = qg.spend_run_token(token, **{k: a for k, a in args.items() if k != "skull"})
        return {"replays_identical_request": bool(first and again)}
    claim = qg.claim_final(token, **args)
    qg.settle_final(claim, {"decision": "proceed", "trace_id": "t"})
    again = qg.claim_final(token, **args)
    other = qg.claim_final(token, **{**args, "skull": "unknown"})
    return {"replays_identical_request": again.status == "replay" and again.answer == {"decision": "proceed", "trace_id": "t"},
            "refuses_another_request": other.status == "conflict"}


def main():
    data = {"$comment": ["M1 (thirteenth review of PR #81): the server's own gate decisions for the inputs the model-based test",
                         "of the browser card plays (sequence | attested | skull [| run confirmed]). Generated by",
                         "scripts/safety/quality_gate_card_model_fixture.py; checked by test_rc122_review13.py. DRAFT."],
            "decisions": decisions(), "run_token": run_token_semantics()}
    open(OUT, "w", encoding="utf-8", newline="\n").write(json.dumps(data, indent=1, ensure_ascii=False) + "\n")
    print(len(data["decisions"]))


if __name__ == "__main__":
    main()
