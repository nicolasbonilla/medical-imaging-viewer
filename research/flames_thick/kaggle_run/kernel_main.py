"""MSTool-AI research - FLAMeS-thick fine-tuning, one Kaggle GPU session (NOT a medical device).

Protocol: docs/research/flames-thick/PROTOCOL.md (pre-registered) of github.com/nicolasbonilla/medical-imaging-viewer,
branch research/flames-thick. Inputs (private Kaggle datasets, CC BY 4.0): FLAMeS fold 0 (Dereskewicz et al.,
J Neuroimaging 2025; F. La Rosa, Zenodo 10.5281/zenodo.17955359) and the MSLesSeg TRAIN split (Guarnera et al.,
Sci Data 2025; Figshare 10.6084/m9.figshare.27919209.v1). Derived weights: "Fine-tuned from FLAMeS fold 0 ...
on MSLesSeg-train; changes by MSTool-AI" (NOTICE.txt inside every exported model).

This file is generated by research/flames_thick/kaggle_run/push.py: CONFIG and the code bundle (the
research/flames_thick package at a git commit, tar.gz, SHA-256 checked) are filled in there.

One session = one kernel. The session:
  1. records the machine (GPU, driver, CPUs, RAM) and installs the frozen environment of the protocol
     (Python 3.10.12 via uv + research/flames_thick/requirements-gpu.lock: nnunetv2 2.8.1, torch 2.14.1+cu126);
  2. finds the two input datasets and checks them (vertex_entry re-checks every file against PROVENANCE.json);
  3. restores the training state ("store") from the previous session's kernel output (kernel source);
  4. runs one supervisor per arm, each on its own GPU (CUDA_VISIBLE_DEVICES), with a soft session deadline
     after which every run PAUSES cleanly (resumable checkpoint) and a hard watchdog before Kaggle's limit;
  5. writes the session record (sessions/<id>.json) next to the store in /kaggle/working (= kernel output).
"""
import base64
import datetime
import glob
import hashlib
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
import time

CONFIG = json.loads(r'''__CONFIG_JSON__''')
CODE_B64 = "__CODE_B64__"

T0 = time.time()
UTC = "%Y-%m-%dT%H:%M:%SZ"
OUT = "/kaggle/working"
STORE = os.path.join(OUT, "store")
INPUT = "/kaggle/input"


def utc(t=None):
    return datetime.datetime.fromtimestamp(T0 if t is None else t, datetime.timezone.utc).strftime(UTC)


SESSION_ID = f"{CONFIG['session']}-{utc().replace(':', '').replace('-', '')}"
REC = {"session": CONFIG["session"], "session_id": SESSION_ID, "kernel": CONFIG.get("kernel"),
       "previous_kernel": CONFIG.get("previous_kernel"), "start_utc": utc(), "git_commit": CONFIG.get("git_commit"),
       "code_sha256": CONFIG.get("code_sha256"), "purpose": CONFIG.get("purpose"), "stages": {}, "runs": {},
       "errors": [], "platform": "kaggle-kernel", "cost_usd": 0.0}


def log(*a):
    print(f"[{utc(time.time())} +{(time.time() - T0) / 60:6.1f} min]", *a, flush=True)


def stage(name):
    REC["stages"][name] = utc(time.time())
    log("=== stage", name)
    save_rec()


def save_rec():
    os.makedirs(os.path.join(OUT, "sessions"), exist_ok=True)
    REC["updated_utc"] = utc(time.time())
    REC["wall_seconds"] = round(time.time() - T0, 1)
    tmp = os.path.join(OUT, "sessions", SESSION_ID + ".json.part")
    with open(tmp, "w") as f:
        json.dump(REC, f, indent=1, default=str)
    os.replace(tmp, os.path.join(OUT, "sessions", SESSION_ID + ".json"))


def sh(cmd, check=True, timeout=3600, quiet=False):
    t = time.time()
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=timeout)
    if not quiet or r.returncode:
        log(f"$ {cmd} -> {r.returncode} ({time.time() - t:.0f}s)")
    if check and r.returncode:
        raise RuntimeError(f"{cmd} failed ({r.returncode}):\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    return r.stdout.strip()


def sha256(path, chunk=1 << 22):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(chunk), b""):
            h.update(b)
    return h.hexdigest()


# ---------------------------------------------------------------------------- 1. machine + environment
def machine():
    q = sh("nvidia-smi --query-gpu=index,name,memory.total,driver_version,pci.bus_id --format=csv,noheader",
           check=False, quiet=True)
    smi = sh("nvidia-smi", check=False, quiet=True)
    cuda = [l for l in smi.splitlines() if "CUDA Version" in l]
    mem = sh("free -g | awk '/Mem:/{print $2}'", check=False, quiet=True)
    env = {k: os.environ.get(k) for k in ("KAGGLE_KERNEL_RUN_TYPE", "KAGGLE_DOCKER_IMAGE", "KAGGLE_CONTAINER_NAME")
           if os.environ.get(k)}
    return {"gpus": [l.strip() for l in q.splitlines() if l.strip()],
            "driver_cuda": cuda[0].strip(" |") if cuda else "", "accelerator_requested": CONFIG.get("accelerator"),
            "cpu_model": sh("lscpu | sed -n 's/^Model name:[[:space:]]*//p' | head -1", check=False, quiet=True),
            "vcpus": os.cpu_count(), "memory_gb": mem, "kaggle_env": env,
            "disk_free_gb": {p: round(shutil.disk_usage(p).free / 1e9, 1) for p in (OUT, "/tmp") if os.path.isdir(p)},
            "system_python": sys.version.split()[0]}


def workdir():
    for p in ("/kaggle/temp", "/tmp"):
        if os.path.isdir(p) and os.access(p, os.W_OK):
            return os.path.join(p, "mstool")
    return "/tmp/mstool"


def unpack_code(work):
    blob = base64.b64decode(CODE_B64)
    got = hashlib.sha256(blob).hexdigest()
    if got != CONFIG["code_sha256"]:
        raise RuntimeError(f"code bundle SHA-256 {got} != {CONFIG['code_sha256']}")
    code = os.path.join(work, "code")
    shutil.rmtree(code, ignore_errors=True)
    with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as t:
        t.extractall(code, **({"filter": "data"} if hasattr(tarfile, "data_filter") else {}))
    return code


def install_env(work, code):
    """Python 3.10.12 venv (uv) with the frozen lock of the protocol (torch 2.14.1+cu126, nnunetv2 2.8.1)."""
    venv = os.path.join(work, "venv")
    sh(f"{sys.executable} -m pip install -q --disable-pip-version-check 'uv{CONFIG.get('uv_spec', '>=0.8,<1')}'")
    uv = f"{sys.executable} -m uv"
    REC["uv_version"] = sh(f"{uv} --version", quiet=True)
    want = CONFIG.get("python", "3.10.12")
    try:
        sh(f"{uv} python install {want}")
        sh(f"{uv} venv --seed --python {want} {venv}")
    except RuntimeError as exc:                # record and fall back to the newest 3.10 uv can find
        REC["errors"].append({"python_install": repr(exc)[:500]})
        sh(f"{uv} python install 3.10")
        sh(f"{uv} venv --seed --python 3.10 {venv}")
    py = os.path.join(venv, "bin", "python")
    lock = os.path.join(code, "flames_thick", "requirements-gpu.lock")
    sh(f"{uv} pip install --python {py} -r {lock} --extra-index-url https://download.pytorch.org/whl/cu126 "
       f"--index-strategy unsafe-best-match", timeout=3600)
    REC["venv_python"] = sh(f"{py} -c 'import sys; print(sys.version.split()[0])'", quiet=True)
    REC["torch"] = sh(f"{py} -c \"import torch; print(torch.__version__, torch.version.cuda, "
                      f"torch.cuda.is_available(), torch.cuda.device_count(), torch.cuda.get_arch_list())\"", quiet=True)
    REC["lock_sha256"] = sha256(lock)
    freeze = sh(f"{py} -m pip freeze", quiet=True).splitlines()
    REC["pip_freeze"] = freeze
    norm = lambda n: n.strip().lower().replace("_", "-").replace(".", "-")
    pins = {norm(l.split("==")[0]): l.split("==")[1].strip() for l in open(lock) if "==" in l and not l.startswith("#")}
    got = {norm(l.split("==")[0]): l.split("==")[1].strip() for l in freeze if "==" in l}
    REC["lock_mismatches"] = {k: [v, got.get(k)] for k, v in pins.items() if got.get(k) != v}
    if REC["lock_mismatches"]:
        log("WARNING lock mismatches:", REC["lock_mismatches"])
    return py


# ---------------------------------------------------------------------------- 2. inputs
def find_provenance(kind):
    hits = []
    for p in glob.glob(os.path.join(INPUT, "**", "PROVENANCE.json"), recursive=True):
        try:
            if json.load(open(p)).get("kind") == kind:
                hits.append(p)
        except Exception:
            pass
    if len(hits) != 1:
        raise RuntimeError(f"expected one input dataset of kind {kind}, found {hits}")
    return hits[0]


def inputs(work):
    fp = find_provenance("mstool-flames-thick-input/flames-fold0")
    mp = find_provenance("mstool-flames-thick-input/mslesseg-train")
    mprov = json.load(open(mp))
    mdir = os.path.dirname(mp)
    # stored as ".zip.bin": Kaggle expands uploaded .zip files and gunzips .nii.gz, which would change the bytes
    z = os.path.join(mdir, mprov["subset_zip"])
    if not os.path.isfile(z):
        raise RuntimeError(f"{z} missing; dataset folder holds {sorted(os.listdir(mdir))[:20]}")
    got = sha256(z)
    if got != mprov["subset_sha256"]:
        raise RuntimeError(f"{z}: SHA-256 {got} != uploaded {mprov['subset_sha256']}")
    REC["inputs"] = {"flames_dir": os.path.dirname(fp), "flames_source": json.load(open(fp))["source"],
                     "mslesseg_zip": z, "mslesseg_zip_sha256": got, "mslesseg_source": mprov["source"]}
    return os.path.dirname(fp), z, mp


# ---------------------------------------------------------------------------- 3. state from the previous session
def restore():
    if os.path.isdir(STORE) and os.listdir(STORE):
        REC["restored_from"] = "already present in /kaggle/working"
        return
    cands = sorted(c for c in glob.glob(os.path.join(INPUT, "**", "store"), recursive=True)
                   if os.path.isdir(os.path.join(c, CONFIG.get("prefix", "flames-thick"))))
    want = CONFIG.get("previous_kernel")
    if not cands:
        if want:
            raise RuntimeError(f"previous session {want} listed but no store found under {INPUT}")
        REC["restored_from"] = None
        return
    if len(cands) > 1:
        raise RuntimeError(f"several previous stores: {cands}")
    shutil.copytree(cands[0], STORE)
    prev_sessions = os.path.join(os.path.dirname(cands[0]), "sessions")
    if os.path.isdir(prev_sessions):
        shutil.copytree(prev_sessions, os.path.join(OUT, "sessions"), dirs_exist_ok=True)
    REC["restored_from"] = cands[0]
    log("restored the store from", cands[0])


def run_state(run_id):
    base = os.path.join(STORE, CONFIG.get("prefix", "flames-thick"), "train", run_id)
    st, ep = {}, []
    try:
        st = json.load(open(os.path.join(base, "status.json")))
    except Exception:
        pass
    try:
        ep = json.load(open(os.path.join(base, "fold_0", "epochs.json")))
    except Exception:
        pass
    return st, ep


# ---------------------------------------------------------------------------- 4. training
def launch(py, code, work, flames_dir, mzip, mprov, run, deadline):
    st, ep = run_state(run["run_id"])
    REC["runs"][run["run_id"]] = {"arm": run["arm"], "gpu_index": run["gpu"], "state_at_start": st.get("state"),
                                  "epochs_done_at_start": len(ep)}
    if st.get("state") in ("completed", "budget_stop"):
        log(run["run_id"], "already", st["state"], "- nothing to do")
        return None
    env = {k: v for k, v in os.environ.items() if not k.startswith(("nnUNet_", "FT_"))}
    env.update({
        "PATH": os.path.dirname(py) + os.pathsep + env.get("PATH", ""),      # nnUNetv2_* console scripts of the venv
        "VIRTUAL_ENV": os.path.dirname(os.path.dirname(py)),
        "PYTHONPATH": code, "nnUNet_extTrainer": os.path.join(code, "flames_thick", "nnunet_ext"),
        "nnUNet_compile": "f", "CUDA_VISIBLE_DEVICES": str(run["gpu"]), "PYTHONUNBUFFERED": "1",
        "FT_RUN_ID": run["run_id"], "FT_ARM": run["arm"], "FT_STORE": "local:" + STORE,
        "FT_PREFIX": CONFIG.get("prefix", "flames-thick"), "FT_WORKDIR": os.path.join(work, "w_" + run["run_id"]),
        "FT_INPUTS": "dir", "FT_FLAMES_DIR": flames_dir, "FT_MSLESSEG_ZIP": mzip, "FT_MSLESSEG_PROVENANCE": mprov,
        "FT_RATE_USD_PER_H": "0", "FT_MAX_COST_USD": "1", "FT_SAFETY": "1", "FT_ATTEMPT_OVERHEAD_S": "0",
        "FT_MAX_HOURS": str(CONFIG.get("max_cumulative_hours", 60)), "FT_RESERVE_S": "1800",
        "FT_SESSION_RESERVE_S": str(CONFIG.get("session_reserve_s", 600)),
        "FT_SESSION_DEADLINE_UTC": utc(deadline), "FT_NPROC": str(CONFIG.get("nproc", 2)),
        "FT_PLATFORM": "kaggle-kernel", "FT_PROVISIONING": "Kaggle free GPU quota",
        "FT_MACHINE_TYPE": f"kaggle-{CONFIG.get('accelerator') or 'cpu'}", "FT_GPU": run.get("gpu_label", ""),
        "FT_IMAGE": f"kaggle kernel {CONFIG.get('kernel')} (system image) + uv venv from requirements-gpu.lock",
        "FT_GIT_COMMIT": CONFIG.get("git_commit", ""), "FT_PURPOSE": run.get("purpose", CONFIG.get("purpose", "")),
    })
    if CONFIG.get("n_proc_da"):
        env["nnUNet_n_proc_DA"] = str(CONFIG["n_proc_da"])
    env.update({k: str(v) for k, v in run.get("env", {}).items()})
    os.makedirs(os.path.join(OUT, "logs"), exist_ok=True)
    lf = open(os.path.join(OUT, "logs", f"{SESSION_ID}_{run['run_id']}.log"), "w")
    log("launching", run["run_id"], "arm", run["arm"], "on GPU", run["gpu"], "overrides", run.get("env", {}))
    p = subprocess.Popen([py, "-m", "flames_thick.vertex_entry"], env=env, stdout=lf, stderr=subprocess.STDOUT,
                         cwd=work, start_new_session=True)
    return p, lf


def gpu_sanity(py, code, flames_dir, mzip):
    """Unchanged FLAMeS fold 0 on one MSLesSeg-train scan, on GPU 0 (compared locally with the CPU reference map)."""
    out = os.path.join(OUT, "gpu_sanity")
    os.makedirs(out, exist_ok=True)
    env = dict(os.environ, PYTHONPATH=code, CUDA_VISIBLE_DEVICES="0", PYTHONUNBUFFERED="1",
               PATH=os.path.dirname(py) + os.pathsep + os.environ.get("PATH", ""))
    try:
        r = subprocess.run([py, os.path.join(code, "flames_thick", "kaggle_run", "gpu_sanity.py"), flames_dir, mzip,
                            CONFIG["gpu_sanity"], out], env=env, capture_output=True, text=True, timeout=1800)
        REC["gpu_sanity"] = (json.loads(r.stdout.strip().splitlines()[-1]) if r.returncode == 0
                             else {"error": (r.stdout[-1500:] + r.stderr[-2500:])})
    except Exception as exc:
        REC["gpu_sanity"] = {"error": repr(exc)[:1000]}
    log("gpu sanity:", REC["gpu_sanity"])


def kill_all():
    for sig in ("TERM", "KILL"):
        subprocess.run(["pkill", f"-{sig}", "-f", "flames_thick.vertex_entry"], capture_output=True)
        time.sleep(20)


def progress_line():
    parts = []
    for run in CONFIG["runs"]:
        st, ep = run_state(run["run_id"])
        last = ep[-1] if ep else {}
        parts.append(f"{run['run_id']}: {st.get('state', '-')} epochs={len(ep)} last_s={last.get('seconds')} "
                     f"dice={last.get('pseudo_dice')}")
    return " | ".join(parts)


def summarize():
    for run in CONFIG["runs"]:
        st, ep = run_state(run["run_id"])
        r = REC["runs"].setdefault(run["run_id"], {})
        start = r.get("epochs_done_at_start", 0)
        new = [e for e in ep[start:] if e.get("seconds")]
        secs = sorted(e["seconds"] for e in new)
        r.update({"state_at_end": st.get("state"), "status": st, "epochs_done_at_end": len(ep),
                  "epochs_this_session": len(ep) - start,
                  "median_s_per_epoch": secs[len(secs) // 2] if secs else None,
                  "iters": new[-1].get("iters") if new else None})
        base = os.path.join(STORE, CONFIG.get("prefix", "flames-thick"), "train", run["run_id"])
        if st.get("state") == "completed" and os.path.isfile(os.path.join(base, "model.tar.gz")):
            for f in ("checkpoint_latest.pth",):             # the final model is exported: drop the resume state
                p = os.path.join(base, "fold_0", f)
                if os.path.isfile(p):
                    os.remove(p)
            r["model_tar_sha256"] = open(os.path.join(base, "model.tar.gz.sha256")).read().strip()


def main():
    hard = T0 + CONFIG["hard_hours"] * 3600
    soft = T0 + CONFIG["soft_hours"] * 3600
    REC["soft_deadline_utc"], REC["hard_deadline_utc"] = utc(soft), utc(hard)
    procs = {}
    try:
        stage("machine")
        REC["machine"] = machine()
        log(json.dumps(REC["machine"], indent=1))
        work = workdir()
        os.makedirs(work, exist_ok=True)
        stage("code")
        code = unpack_code(work)
        stage("env")
        py = install_env(work, code)
        log("venv:", REC["venv_python"], REC["torch"])
        stage("inputs")
        flames_dir, mzip, mprov = inputs(work)
        stage("restore")
        restore()
        if CONFIG.get("gpu_sanity"):
            stage("gpu_sanity")
            gpu_sanity(py, code, flames_dir, mzip)
        stage("train")
        for run in CONFIG["runs"]:
            x = launch(py, code, work, flames_dir, mzip, mprov, run, soft)
            if x:
                procs[run["run_id"]] = x
            time.sleep(CONFIG.get("stagger_s", 0))
        last = 0
        while any(p.poll() is None for p, _ in procs.values()):
            if time.time() > hard:
                REC["errors"].append({"hard_deadline": utc(time.time())})
                log("HARD DEADLINE: killing the training processes")
                kill_all()
                break
            if time.time() - last > CONFIG.get("progress_every_s", 300):
                last = time.time()
                log(progress_line())
                save_rec()
            time.sleep(15)
        for rid, (p, lf) in procs.items():
            REC["runs"][rid]["supervisor_returncode"] = p.poll()
            lf.close()
        stage("end_train")
    except Exception as exc:
        import traceback
        REC["errors"].append({"error": repr(exc)[:2000], "trace": traceback.format_exc()[-4000:]})
        log("FAILED:", repr(exc))
        if procs:
            kill_all()
    finally:
        try:
            summarize()
        except Exception as exc:
            REC["errors"].append({"summarize": repr(exc)[:500]})
        REC["end_utc"] = utc(time.time())
        REC["gpu_hours"] = round((time.time() - T0) / 3600, 3)   # the GPUs are attached for the whole session
        save_rec()
        log("session record:", json.dumps({k: REC[k] for k in ("session_id", "wall_seconds", "gpu_hours", "runs",
                                                                "errors")}, indent=1, default=str)[:6000])
        log(progress_line())
        sh(f"du -sh {OUT} && find {OUT} -type f | head -100", check=False)


if __name__ == "__main__":
    main()
